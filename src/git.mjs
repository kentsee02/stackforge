import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { run } from './process.mjs';

export async function gitIdentity(options, command = run) {
  const read = async key => {
    try { return (await command('git', ['config', '--get', key], { cwd: tmpdir(), timeout: 8000 })).trim(); }
    catch { return ''; }
  };
  const [name, email] = await Promise.all([options.authorName || read('user.name'), options.authorEmail || read('user.email')]);
  return { name, email };
}

export async function githubAccount(command = run) {
  const account = (await command('gh', ['api', '--hostname', 'github.com', 'user', '--jq', '.login'], { timeout: 15000 })).trim();
  if (!/^[a-zA-Z0-9][a-zA-Z0-9-]{0,38}$/.test(account)) throw new Error('无法确认当前 GitHub 账号，请运行 gh auth login 后重试。');
  return account;
}

export async function initializeGit(path, options, command = run, log = () => {}) {
  await command('git', ['init', '-b', 'main'], { cwd: path, log });
  if (!options.commit) return;
  const identity = await gitIdentity(options, command);
  if (!identity.name || !identity.email) throw new Error('首次提交需要姓名和邮箱。请填写提交身份，或只选择初始化 Git。');
  // Apply identity only inside the newly generated repository, never globally.
  if (options.authorName) await command('git', ['config', '--local', 'user.name', options.authorName], { cwd: path });
  if (options.authorEmail) await command('git', ['config', '--local', 'user.email', options.authorEmail], { cwd: path });
  await command('git', ['add', '--all'], { cwd: path, log });
  await command('git', ['commit', '-m', 'Initial project generated by StackForge'], { cwd: path, log });
}

export async function publishProject(path, options, report = () => {}, command = run) {
  const log = text => report({ type: 'log', message: text });
  const account = await githubAccount(command);
  const fullName = `${account}/${options.repoName}`;
  const marker = join(path, '.git', 'stackforge-remote.json');
  let binding;
  try { binding = JSON.parse(await readFile(marker, 'utf8')); }
  catch (error) { if (error.code !== 'ENOENT') throw new Error('远程仓库记录损坏，请检查项目的 Git 配置。'); }
  if (binding) {
    // Retry only a repository created by this job, after verifying its identity.
    if (binding.full_name !== fullName) throw new Error('GitHub 账号已变更，请切回创建该仓库的账号后重试。');
    const remote = JSON.parse(await command('gh', ['api', '--hostname', 'github.com', `repos/${fullName}`, '--jq', '{id,full_name,clone_url,html_url,private}'], { timeout: 30000 }));
    if (remote.id !== binding.id || remote.private !== (options.visibility === 'private')) throw new Error('远程仓库身份或可见性已改变，已停止推送。');
    binding = remote;
  } else {
    // A name collision is an error. Never reuse or write to an unrelated repo.
    report({ type: 'step', message: `在 ${account} 下创建${options.visibility === 'private' ? '私有' : '公开'}仓库`, progress: 96 });
    binding = JSON.parse(await command('gh', ['api', '--hostname', 'github.com', 'user/repos', '--method', 'POST', '--raw-field', `name=${options.repoName}`, '--field', `private=${options.visibility === 'private'}`, '--jq', '{id,full_name,clone_url,html_url,private}'], { timeout: 30000 }));
    if (binding.full_name !== fullName || !Number.isInteger(binding.id) || binding.private !== (options.visibility === 'private')) throw new Error('GitHub 返回了意外的仓库信息，请在 GitHub 中检查创建结果。');
    await writeFile(marker, JSON.stringify(binding), { mode: 0o600 });
  }
  const expectedUrl = `https://github.com/${fullName}.git`;
  let origin;
  try { origin = (await command('git', ['remote', 'get-url', 'origin'], { cwd: path })).trim(); }
  catch { /* no origin yet */ }
  if (origin && origin !== expectedUrl) throw new Error('本地 origin 指向其他仓库，已停止推送。');
  if (!origin) await command('git', ['remote', 'add', 'origin', expectedUrl], { cwd: path });
  report({ type: 'step', message: '推送首次提交到 GitHub', progress: 98 });
  // Use gh's existing credential store for this command, without changing the
  // user's global Git configuration or storing credentials in project files.
  await command('git', ['-c', 'credential.helper=', '-c', 'credential.https://github.com.helper=!gh auth git-credential', 'push', '--set-upstream', 'origin', 'main'], { cwd: path, log, env: { ...process.env, GIT_TERMINAL_PROMPT: '0', GH_PROMPT_DISABLED: '1' } });
  return { status: 'published', url: `https://github.com/${fullName}`, visibility: options.visibility };
}
